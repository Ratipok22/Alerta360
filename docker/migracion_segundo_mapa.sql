-- ============================================================
-- Migracion: integrar el modulo de prediccion de demanda (ML / "segundo
-- mapa") que trabajo Alexsander, conservando lo que ya construimos
-- (rol soporte, los 17 codigos de tipo_emergencia, archivo_url en TEXT).
--
-- Que hace:
--   1. Cambia emergencia.zona.id_zona de integer a varchar(20) (ahora son
--      codigos INE reales, ej. "INE24-05101-01", no numeros correlativos).
--   2. Quita la columna emergencia.zona.actividad (ya no se usa).
--   3. Agrega una validacion de coordenadas a zona.
--   4. Crea las 3 tablas nuevas del modulo ML: modelo_demanda, prediccion,
--      registro_historico.
--
-- Que NO hace (a proposito, para no perder avances propios):
--   - No toca emergencia.usuario ni su CHECK de roles (sigue permitiendo
--     'soporte').
--   - No toca emergencia.tipo_emergencia (se quedan los 17 codigos).
--   - No toca emergencia.ticket.archivo_url (se queda en TEXT).
--   - No agrega la columna ticket.id_asignado (se decidio no incluirla).
--   - No importa la tabla publica "public.usuario": es un resto suelto del
--     dump de Alexsander que ninguna parte de la app usa.
--
-- Las 5 zonas de prueba actuales (Valparaiso/Vina/Concon genericas) se
-- reemplazan por las 281 zonas reales -- no tenian uso real todavia, asi
-- que no hay perdida de datos relevante. Las emergencias ya creadas
-- quedan con id_zona en NULL (los codigos nuevos no son compatibles con
-- los numeros viejos 1-5), que es exactamente como ya se crean las
-- emergencias desde el formulario (nunca se asigna zona ahi).
--
-- Correr completo de una vez (es una sola transaccion: si algo falla, no
-- deja nada a medio camino).
-- ============================================================

BEGIN;

-- 0) Seguro para poder re-correr el script si un intento anterior quedo a
--    medio camino (p.ej. si alcanzo a crear estas tablas pero fallo antes
--    de terminar) -- estan vacias en ese caso, no se pierde nada real.
DROP TABLE IF EXISTS emergencia.prediccion CASCADE;
DROP TABLE IF EXISTS emergencia.registro_historico CASCADE;
DROP TABLE IF EXISTS emergencia.modelo_demanda CASCADE;

-- 1) Desacoplar la FK existente hacia zona (su tipo va a cambiar)
ALTER TABLE emergencia.emergencia DROP CONSTRAINT fk_emergencia_zona;

-- 2) Limpiar la referencia antes de cambiar el tipo de la columna
UPDATE emergencia.emergencia SET id_zona = NULL WHERE id_zona IS NOT NULL;

-- 3) Vaciar las 5 zonas de prueba (se reemplazan por las 281 reales)
TRUNCATE TABLE emergencia.zona;

-- 4) Quitar la columna que ya no se usa
ALTER TABLE emergencia.zona DROP COLUMN actividad;

-- 5) Cambiar la clave primaria de zona a texto (codigos INE)
ALTER TABLE emergencia.zona ALTER COLUMN id_zona DROP IDENTITY IF EXISTS;
ALTER TABLE emergencia.zona ALTER COLUMN id_zona TYPE character varying(20);
ALTER TABLE emergencia.zona ALTER COLUMN latitud_minima SET NOT NULL;
ALTER TABLE emergencia.zona ALTER COLUMN longitud_minima SET NOT NULL;
ALTER TABLE emergencia.zona ALTER COLUMN latitud_maxima SET NOT NULL;
ALTER TABLE emergencia.zona ALTER COLUMN longitud_maxima SET NOT NULL;

-- 6) Validacion de coordenadas geograficas (igual a la del dump de Alexsander)
ALTER TABLE emergencia.zona ADD CONSTRAINT chk_zona_limites_geograficos CHECK (
    latitud_minima < latitud_maxima AND
    longitud_minima < longitud_maxima AND
    latitud_minima BETWEEN -90 AND 90 AND
    latitud_maxima BETWEEN -90 AND 90 AND
    longitud_minima BETWEEN -180 AND 180 AND
    longitud_maxima BETWEEN -180 AND 180
);

-- 7) Actualizar emergencia.emergencia.id_zona al mismo tipo y restaurar la FK
ALTER TABLE emergencia.emergencia ALTER COLUMN id_zona TYPE character varying(20);
ALTER TABLE emergencia.emergencia
    ADD CONSTRAINT fk_emergencia_zona FOREIGN KEY (id_zona) REFERENCES emergencia.zona(id_zona);

-- 8) Tablas nuevas del modulo de prediccion de demanda (ML)
CREATE TABLE emergencia.modelo_demanda (
    id_modelo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entrenado_en timestamp without time zone,
    mae double precision,
    baseline_mae double precision,
    modelo_ganador character varying(100),
    importancia_variables jsonb,
    comparacion_modelos jsonb,
    ruta_artefacto character varying(255),
    n_registros integer,
    datos_desde date,
    datos_hasta date,
    activo boolean NOT NULL DEFAULT false
);

CREATE TABLE emergencia.prediccion (
    id_prediccion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_modelo integer REFERENCES emergencia.modelo_demanda(id_modelo),
    id_zona character varying(20) NOT NULL REFERENCES emergencia.zona(id_zona),
    codigo_emergencia character varying(20) NOT NULL REFERENCES emergencia.tipo_emergencia(codigo_emergencia),
    periodo_inicio character varying(50),
    generado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    casos_esperados double precision,
    CONSTRAINT chk_prediccion_casos CHECK (casos_esperados IS NULL OR casos_esperados >= 0)
);
CREATE INDEX idx_prediccion_generado ON emergencia.prediccion (generado_en);
CREATE INDEX idx_prediccion_zona ON emergencia.prediccion (id_zona);

CREATE TABLE emergencia.registro_historico (
    id_registro integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_zona character varying(20) NOT NULL REFERENCES emergencia.zona(id_zona),
    codigo_emergencia character varying(20) NOT NULL REFERENCES emergencia.tipo_emergencia(codigo_emergencia),
    timestamp_registro timestamp without time zone,
    fecha date NOT NULL,
    dia_semana integer,
    mes integer,
    bloque_horario integer,
    cantidad_emergencias integer NOT NULL DEFAULT 0,
    recursos_utilizados integer,
    temperatura_c double precision,
    viento_kmh double precision,
    precipitacion_mm double precision,
    CONSTRAINT chk_historico_cantidad CHECK (cantidad_emergencias >= 0)
);
CREATE INDEX idx_historico_zona_fecha ON emergencia.registro_historico (id_zona, fecha);

COMMIT;
